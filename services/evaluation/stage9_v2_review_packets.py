PACKET_FILENAMES = (
    "alerts.json",
    "analogy.json",
    "clustering.json",
    "entity-linking.json",
)

SOURCE_ANNOTATION_NOTICE = (
    "Existing source annotations were produced or checked only by automation. They are untrusted, "
    "excluded from reviewer tasks, and must not be reconstructed before independent review."
)


class ReviewPacketError(ValueError):
    """A review-packet source has an unexpected shape or cannot be safely transformed."""


def _relative(path: Path) -> str:
    try:
        return path.relative_to(PROJECT_ROOT).as_posix()
    except ValueError as exc:
        raise ReviewPacketError(f"source path must be below the project root: {path}") from exc


def _source_record(path: Path) -> dict[str, str]:
    return {"path": _relative(path), "sha256": sha256_file(path)}


def _load_object(path: Path) -> dict[str, Any]:
    try:
        raw = json.loads(path.read_bytes())
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ReviewPacketError(f"cannot load {_relative(path)}: {exc}") from exc
    if not isinstance(raw, dict):
        raise ReviewPacketError(f"{_relative(path)} must contain a JSON object")
    return raw


def _object_list(raw: Mapping[str, Any], key: str, source: Path) -> list[dict[str, Any]]:
    value = raw.get(key)
    if not isinstance(value, list) or not all(isinstance(item, dict) for item in value):
        raise ReviewPacketError(f"{_relative(source)}.{key} must be a list of objects")
    return value


def _string(raw: Mapping[str, Any], key: str, where: str) -> str:
    value = raw.get(key)
    if not isinstance(value, str) or not value:
        raise ReviewPacketError(f"{where}.{key} must be a non-empty string")
    return value


def _copy_fields(raw: Mapping[str, Any], fields: Sequence[str]) -> dict[str, Any]:
    """Copy an allowlisted set of JSON fields while preserving explicit nulls."""
    return {field: raw[field] for field in fields if field in raw}


def _source_refs(raw_refs: Any, where: str) -> list[dict[str, Any]]:
    if not isinstance(raw_refs, list) or not all(isinstance(ref, dict) for ref in raw_refs):
        raise ReviewPacketError(f"{where} must be a list of source-reference objects")
    allowed = ("id", "title", "publisher", "url", "accessed", "kind")
    return [_copy_fields(ref, allowed) for ref in raw_refs]


def _onset_source_refs(
    raw_refs: Any,
    *,
    allowed_ids: set[str],
    where: str,
) -> list[dict[str, Any]]:
    """Copy only evidence explicitly cited by onset inputs, never outcome-only references."""

    refs = _source_refs(raw_refs, where)
    available_ids = {
        ref["id"] for ref in refs if isinstance(ref.get("id"), str) and bool(ref["id"])
    }
    missing = sorted(allowed_ids - available_ids)
    if missing:
        raise ReviewPacketError(f"{where} is missing onset source ids: {', '.join(missing)}")
    return [ref for ref in refs if ref.get("id") in allowed_ids]


def _base_review_fields() -> dict[str, Any]:
    return {
        "confidence": None,
        "decision": None,
        "evidence_source_ids": [],
        "rationale": None,
        "reviewed_on": None,
        "reviewer_id": None,
    }


def _review_slots(*, extra_fields: Sequence[str] = ()) -> dict[str, dict[str, Any]]:
    def blank() -> dict[str, Any]:
        fields = _base_review_fields()
        fields.update({field: None for field in extra_fields})
        return fields

    adjudication = blank()
    adjudication["adjudicator_id"] = adjudication.pop("reviewer_id")
    return {
        "reviewer_a": blank(),
        "reviewer_b": blank(),
        "adjudication": adjudication,
    }


def _packet_header(
    *,
    domain: str,
    sources: Sequence[Path],
    review_contract: Mapping[str, Any],
) -> dict[str, Any]:
    return {
        "schema": PACKET_SCHEMA,
        "protocol_id": PROTOCOL_ID,
        "domain": domain,
        "generator": GENERATOR_ID,
        "human_review_status": "not_started",
        "source_annotations": {
            "included_in_tasks": False,
            "status": "automated_untrusted",
            "notice": SOURCE_ANNOTATION_NOTICE,
        },
        "review_contract": dict(review_contract),
        "sources": [_source_record(path) for path in sources],
    }


def build_entity_linking_packet() -> dict[str, Any]:
    """Build entity-linking tasks without expected links, NIL labels, case tags, or notes."""
    target_raw = _load_object(ENTITY_TARGETS_FILE)
    targets = _object_list(target_raw, "targets", ENTITY_TARGETS_FILE)
    sorted_targets = sorted(
        targets,
        key=lambda target: (
            _string(target, "canonical_name", "entity target").casefold(),
            _string(target, "target_id", "entity target"),
        ),
    )
    target_handles = {
        _string(target, "target_id", "entity target"): f"entity-candidate-{index:03d}"
        for index, target in enumerate(sorted_targets, start=1)
    }

    candidates: list[dict[str, Any]] = []
    for target in sorted_targets:
        raw_target_id = _string(target, "target_id", "entity target")
        parent = target.get("parent")
        parent_candidate_id = None
        relationship_type = None
        if parent is not None:
            if not isinstance(parent, dict):
                raise ReviewPacketError(f"entity target {raw_target_id}.parent must be an object")
            parent_id = _string(parent, "target_id", f"entity target {raw_target_id}.parent")
            try:
                parent_candidate_id = target_handles[parent_id]
            except KeyError as exc:
                raise ReviewPacketError(
                    f"entity target {raw_target_id} names unknown parent {parent_id}"
                ) from exc
            relationship_type = parent.get("relationship_type")

        aliases = target.get("aliases", [])
        if not isinstance(aliases, list) or not all(isinstance(alias, dict) for alias in aliases):
            raise ReviewPacketError(f"entity target {raw_target_id}.aliases must be a list")
        candidate = {
            "candidate_id": target_handles[raw_target_id],
            "source_record_sha256": canonical_json_hash(target),
            **_copy_fields(
                target,
                (
                    "canonical_name",
                    "entity_type",
                    "country",
                    "ticker",
                    "cik",
                    "lei",
                    "website",
                ),
            ),
            "aliases": [
                _copy_fields(
                    alias,
                    ("value", "alias_type", "source", "valid_from", "valid_to"),
                )
                for alias in aliases
            ],
            "parent": (
                {
                    "candidate_id": parent_candidate_id,
                    "relationship_type": relationship_type,
                }
                if parent_candidate_id is not None
                else None
            ),
            "source_refs": _source_refs(
                target.get("authoritative_refs", []),
                f"entity target {raw_target_id}.authoritative_refs",
            ),
        }
        candidates.append(candidate)

    tasks: list[dict[str, Any]] = []
    split_counts: dict[str, int] = {}
    for source in ENTITY_SOURCE_FILES:
        raw = _load_object(source)
        partition = _string(raw, "split", _relative(source))
        mentions = sorted(
            _object_list(raw, "mentions", source),
            key=lambda mention: _string(mention, "mention_id", f"{_relative(source)} mention"),
        )
        split_counts[partition] = len(mentions)
        for mention in mentions:
            context = mention.get("context")
            sentence = mention.get("sentence")
            if not isinstance(context, dict) or not isinstance(sentence, dict):
                raise ReviewPacketError(
                    f"{_relative(source)} mention context and sentence must be objects"
                )
            task_id = f"entity-linking-{len(tasks) + 1:04d}"
            tasks.append(
                {
                    "task_id": task_id,
                    "source_partition": partition,
                    "source_record_sha256": canonical_json_hash(mention),
                    "input": {
                        **_copy_fields(
                            mention,
                            (
                                "language",
                                "document_text",
                                "mention_text",
                                "start",
                                "end",
                                "published_on",
                                "article_url",
                            ),
                        ),
                        "sentence": _copy_fields(
                            sentence,
                            ("index", "text", "start", "end", "previous_text", "next_text"),
                        ),
                        "context": _copy_fields(
                            context,
                            (
                                "source_category",
                                "industry_terms",
                                "location_terms",
                                "co_mention_surfaces",
                            ),
                        ),
                    },
                    "reviews": _review_slots(extra_fields=("selected_candidate_id",)),
                }
            )

    packet = _packet_header(
        domain="entity_linking",
        sources=(*ENTITY_SOURCE_FILES, ENTITY_TARGETS_FILE),
        review_contract={
            "instructions": [
                "Review the mention in its document and sentence context.",
                "Choose one opaque candidate_id from candidate_catalog, or no_matching_entity.",
                "Reviewer A and reviewer B work independently; adjudication begins only afterward.",
            ],
            "decision_values": [
                "linked_entity",
                "no_matching_entity",
                "insufficient_evidence",
            ],
            "confidence_values": ["high", "medium", "low"],
        },
    )
    packet.update(
        {
            "counts": {
                "candidate_entities": len(candidates),
                "tasks": len(tasks),
                "tasks_by_partition": split_counts,
            },
            "candidate_catalog": candidates,
            "tasks": tasks,
        }
    )
    return packet


def build_alert_packet() -> dict[str, Any]:
    """Build alert tasks with as-of evidence but no source label or realised outcome material."""
    tasks: list[dict[str, Any]] = []
    split_counts: dict[str, int] = {}
    for source in ALERT_SOURCE_FILES:
        raw = _load_object(source)
        partition = _string(raw, "split", _relative(source))
        cases = sorted(
            _object_list(raw, "cases", source),
            key=lambda case: _string(case, "case_id", f"{_relative(source)} case"),
        )
        split_counts[partition] = len(cases)
        for case in cases:
            onset = case.get("onset")
            target = case.get("target")
            if not isinstance(onset, dict) or not isinstance(target, dict):
                raise ReviewPacketError(
                    f"{_relative(source)} case onset and target must be objects"
                )
            indicators = onset.get("indicators", [])
            if not isinstance(indicators, list) or not all(
                isinstance(indicator, dict) for indicator in indicators
            ):
                raise ReviewPacketError(f"{_relative(source)} case onset.indicators must be a list")
            onset_source_ids: set[str] = set()
            for indicator in indicators:
                raw_source_ids = indicator.get("source_ids", [])
                if not isinstance(raw_source_ids, list) or not all(
                    isinstance(source_id, str) and bool(source_id) for source_id in raw_source_ids
                ):
                    raise ReviewPacketError(
                        f"{_relative(source)} case onset indicator source_ids must be strings"
                    )
                onset_source_ids.update(raw_source_ids)

            task_id = f"alert-{len(tasks) + 1:04d}"
            tasks.append(
                {
                    "task_id": task_id,
                    "source_partition": partition,
                    "source_record_sha256": canonical_json_hash(case),
                    "input": {
                        **_copy_fields(
                            case,
                            (
                                "window",
                                "evaluation_as_of",
                                "evaluation_horizons",
                                "evaluation_end",
                            ),
                        ),
                        "target": _copy_fields(target, ("type", "name", "geography")),
                        "onset": {
                            **_copy_fields(onset, ("observation_start", "summary")),
                            "indicators": [
                                _copy_fields(
                                    indicator,
                                    (
                                        "key",
                                        "description",
                                        "observed_on",
                                        "source_ids",
                                        "value",
                                        "unit",
                                    ),
                                )
                                for indicator in indicators
                            ],
                        },
                        "source_refs": _onset_source_refs(
                            case.get("source_refs", []),
                            allowed_ids=onset_source_ids,
                            where=f"{_relative(source)} case source_refs",
                        ),
                    },
                    "reviews": _review_slots(extra_fields=("event_start_date", "risk_type")),
                }
            )

    packet = _packet_header(
        domain="alerts",
        sources=ALERT_SOURCE_FILES,
        review_contract={
            "instructions": [
                "Use the dated as-of evidence and cited sources to assess only the stated horizon.",
                "Independently determine whether a qualifying event occurred and assign its risk type.",
                "Do not infer a decision from ordering, task ids, or the source partition.",
                "Reviewer A and reviewer B work independently; adjudication begins only afterward.",
            ],
            "decision_values": [
                "event_occurred_in_horizon",
                "no_qualifying_event_in_horizon",
                "insufficient_evidence",
            ],
            "confidence_values": ["high", "medium", "low"],
        },
    )
    packet.update(
        {
            "counts": {
                "tasks": len(tasks),
                "tasks_by_partition": split_counts,
            },
            "tasks": tasks,
        }
    )
    return packet


def _episode_candidates() -> list[dict[str, Any]]:
    episodes: list[dict[str, Any]] = []
    for source in EPISODE_CATALOG_FILES:
        raw = _load_object(source)
        episodes.extend(_object_list(raw, "episodes", source))

    sorted_episodes = sorted(
        episodes,
        key=lambda episode: (
            _string(episode, "onset_date", "historical episode"),
            _string(episode, "slug", "historical episode"),
        ),
    )
    if len({_string(episode, "id", "historical episode") for episode in sorted_episodes}) != len(
        sorted_episodes
    ):
        raise ReviewPacketError("historical episode candidate ids must be unique")

    slug_to_handle = {
        _string(episode, "slug", "historical episode"): f"episode-candidate-{index:03d}"
        for index, episode in enumerate(sorted_episodes, start=1)
    }
    candidates: list[dict[str, Any]] = []
    for episode in sorted_episodes:
        slug = _string(episode, "slug", "historical episode")
        parent_slug = episode.get("parent_slug")
        parent_candidate_id = None
        if parent_slug is not None:
            if not isinstance(parent_slug, str) or parent_slug not in slug_to_handle:
                raise ReviewPacketError(
                    f"historical episode {slug} names unknown parent {parent_slug!r}"
                )
            parent_candidate_id = slug_to_handle[parent_slug]

        indicators = episode.get("onset_indicators", [])
        if not isinstance(indicators, list) or not all(
            isinstance(indicator, dict) for indicator in indicators
        ):
            raise ReviewPacketError(f"historical episode {slug}.onset_indicators must be a list")
        onset_source_ids: set[str] = set()
        for indicator in indicators:
            source_id = indicator.get("source_id")
            if not isinstance(source_id, str) or not source_id:
                raise ReviewPacketError(
                    f"historical episode {slug}.onset_indicators source_id must be a string"
                )
            onset_source_ids.add(source_id)
        candidates.append(
            {
                "candidate_id": slug_to_handle[slug],
                "source_record_sha256": canonical_json_hash(episode),
                **_copy_fields(
                    episode,
                    (
                        "name",
                        "episode_type",
                        "onset_date",
                        "geography",
                        "affected_industries",
                        "regime_tags",
                        "onset_summary",
                    ),
                ),
                "parent_candidate_id": parent_candidate_id,
                "onset_indicators": [
                    {
                        **_copy_fields(
                            indicator,
                            ("key", "value", "unit", "as_of", "source_id"),
                        ),
                        "description": indicator.get("label"),
                    }
                    for indicator in indicators
                ],
                "source_refs": _onset_source_refs(
                    episode.get("source_refs", []),
                    allowed_ids=onset_source_ids,
                    where=f"historical episode {slug}.source_refs",
                ),
            }
        )
    return candidates


def build_analogy_packet() -> dict[str, Any]:
    """Build analogy queries without expected/acceptable ids, counterexample flags, or notes."""
    raw = _load_object(ANALOGY_GOLD_FILE)
    pairs = sorted(
        _object_list(raw, "pairs", ANALOGY_GOLD_FILE),
        key=lambda pair: _string(pair, "pair_id", "analogy pair"),
    )
    candidates = _episode_candidates()
    tasks: list[dict[str, Any]] = []
    for pair in pairs:
        tasks.append(
            {
                "task_id": f"analogy-{len(tasks) + 1:04d}",
                "source_record_sha256": canonical_json_hash(pair),
                "input": _copy_fields(
                    pair,
                    (
                        "title",
                        "summary",
                        "as_of",
                        "episode_types",
                        "regime_tags",
                        "geographies",
                        "industries",
                    ),
                ),
                "reviews": _review_slots(
                    extra_fields=(
                        "primary_candidate_ids",
                        "secondary_candidate_ids",
                        "counterexample_needed",
                    )
                ),
            }
        )

    packet = _packet_header(
        domain="analogy",
        sources=(ANALOGY_GOLD_FILE, *EPISODE_CATALOG_FILES),
        review_contract={
            "instructions": [
                "Compare each as-of query only with onset-side candidate material.",
                "Select the strongest primary analogies and any defensible secondary analogies.",
                "Record whether a counterexample is needed without consulting source answer fields.",
                "Reviewer A and reviewer B work independently; adjudication begins only afterward.",
            ],
            "decision_values": [
                "analogy_candidates_selected",
                "no_defensible_analogy",
                "insufficient_evidence",
            ],
            "confidence_values": ["high", "medium", "low"],
        },
    )
    packet.update(
        {
            "counts": {
                "candidate_episodes": len(candidates),
                "tasks": len(tasks),
            },
            "candidate_catalog": candidates,
            "tasks": tasks,
        }
    )
    return packet


def build_clustering_packet() -> dict[str, Any]:
    """Build the empty, grouped collection contract for a genuine clustering review corpus."""
    packet = _packet_header(
        domain="clustering",
        sources=(),
        review_contract={
            "instructions": [
                "Collect article pairs in groups built around one anchor event.",
                "Each group must contain plausible same-event pairs and hard different-event pairs.",
                "Strip automated similarity scores, cluster ids, and predicted pair decisions.",
                "Reviewer A and reviewer B label each pair independently.",
                "Reveal both reviews to the adjudicator only after both independent reviews are final.",
            ],
            "decision_values": ["same_event", "different_event", "insufficient_evidence"],
            "confidence_values": ["high", "medium", "low"],
        },
    )
    packet.update(
        {
            "status": "collection_required_no_existing_corpus",
            "counts": {
                "collected_groups": 0,
                "collected_pairs": 0,
                "minimum_groups": 20,
                "minimum_pairs": 100,
                "minimum_same_event_after_adjudication": 50,
                "minimum_different_event_after_adjudication": 50,
            },
            "collection_instructions": [
                "Collect at least 20 groups and at least 100 total pairs.",
                "After adjudication, retain at least 50 same-event and 50 different-event pairs.",
                "Every group must contain both pair classes; use near-time, same-entity, or same-topic "
                "hard negatives rather than easy unrelated negatives.",
                "Include multiple publishers, event types, geographies, and publication-time gaps; "
                "do not let one event family dominate the packet.",
                "Keep full source title, URL, publisher, publication time, and enough original or "
                "licensed context for a reviewer to decide event identity.",
                "Assign opaque article and pair ids. Keep collection order unrelated to the expected "
                "decision and do not add automated scores or predictions.",
                "Resolve disagreements by evidence-backed adjudication; uncertainty stays explicit "
                "and does not count toward either class minimum.",
            ],
            "group_schema_template": {
                "group_id": "cluster-group-NNN",
                "anchor_event_context": {
                    "event_window_start": None,
                    "event_window_end": None,
                    "geographies": [],
                    "entities": [],
                    "topic_context": None,
                },
                "pairs": [
                    {
                        "pair_id": "cluster-pair-NNNN",
                        "article_a": {
                            "article_id": "article-NNNN",
                            "title": None,
                            "publisher": None,
                            "published_at": None,
                            "url": None,
                            "context": None,
                        },
                        "article_b": {
                            "article_id": "article-NNNN",
                            "title": None,
                            "publisher": None,
                            "published_at": None,
                            "url": None,
                            "context": None,
                        },
                        "reviews": _review_slots(),
                    }
                ],
            },
            "groups": [],
        }
    )
    return packet


def build_review_packets() -> dict[str, dict[str, Any]]:
    """Build every domain packet and a manifest that hashes their canonical bytes."""
    packets = {
        "alerts.json": build_alert_packet(),
        "analogy.json": build_analogy_packet(),
        "clustering.json": build_clustering_packet(),
        "entity-linking.json": build_entity_linking_packet(),
    }
    if tuple(sorted(packets)) != PACKET_FILENAMES:
        raise ReviewPacketError("packet filename set drifted from the declared contract")

    sources = sorted(
        {
            source["path"]: source for packet in packets.values() for source in packet["sources"]
        }.values(),
        key=lambda source: source["path"],
    )
    manifest = {
        "schema": MANIFEST_SCHEMA,
        "protocol_id": PROTOCOL_ID,
        "generator": GENERATOR_ID,
        "human_review_status": "not_started",
        "source_annotations": {
            "included_in_tasks": False,
            "status": "automated_untrusted",
            "notice": SOURCE_ANNOTATION_NOTICE,
        },
        "review_process": {
            "reviewer_a": "independent_blinded_review",
            "reviewer_b": "independent_blinded_review",
            "adjudication": "begins_after_both_independent_reviews",
        },
        "domains": {
            "alerts": {
                "artifact": "alerts.json",
                "tasks": packets["alerts.json"]["counts"]["tasks"],
            },
            "analogy": {
                "artifact": "analogy.json",
                "tasks": packets["analogy.json"]["counts"]["tasks"],
            },
            "clustering": {
                "artifact": "clustering.json",
                "collected_tasks": packets["clustering.json"]["counts"]["collected_pairs"],
                "minimum_tasks": packets["clustering.json"]["counts"]["minimum_pairs"],
            },
            "entity_linking": {
                "artifact": "entity-linking.json",
                "tasks": packets["entity-linking.json"]["counts"]["tasks"],
            },
        },
        "sources": sources,
        "artifacts": {
            filename: {"sha256": canonical_json_hash(packet)}
            for filename, packet in sorted(packets.items())
        },
    }
    return {"manifest.json": manifest, **packets}


def write_review_packets(output_dir: Path = OUTPUT_ROOT) -> tuple[Path, ...]:
    """Materialize all packets atomically per file and return their stable filename order."""
    output_dir.mkdir(parents=True, exist_ok=True)
    built = build_review_packets()
    paths: list[Path] = []
    for filename in sorted(built):
        path = output_dir / filename
        temporary = output_dir / f".{filename}.tmp"
        temporary.write_bytes(canonical_json_bytes(built[filename]))
        temporary.replace(path)
        paths.append(path)
    return tuple(paths)


def main() -> int:
    for path in write_review_packets():
        print(_relative(path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


