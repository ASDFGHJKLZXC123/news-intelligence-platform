"""Build blinded human-review packets for the Stage 9 v2 validation cycle.

The v1 evaluation artifacts are frozen.  This module prepares a separate v2 review workspace from
only the material that is still eligible for review:

* entity-linking ``train`` and ``development`` mentions;
* alert ``train`` and ``development`` cases;
* the existing unsplit analogy gold queries and their historical-episode candidate catalog; and
* an empty clustering collection contract, because no genuine clustering corpus exists yet.

Source annotations are inputs to be audited, not truth.  Gold labels, expected identifiers,
realised outcomes, notes, and source record identifiers that encode an answer are therefore never
copied into a task.  Each task receives an opaque id and a one-way hash of its full source record so
review results can be reconciled later without unblinding the reviewers.

All output is canonical JSON: UTF-8, sorted keys, compact separators, and one trailing newline.
There is no clock, random seed, host path, or reviewer claim in the generated bytes.
"""

