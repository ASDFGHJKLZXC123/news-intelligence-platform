"""The daily brief's deterministic section material (report-generation spec, ADR 0009).

The last purely deterministic step before composition. Given the selected inputs
(:class:`~services.reports.contracts.BriefInputs`) and the loaded context
(:class:`~services.reports.context.BriefContext`), this module lays out *the brief's skeleton*:
which sections exist, in what order, and -- for the sections that are tables rather than prose --
their exact rows.

What this module does not do is the whole point of it:

* **It writes no prose.** Every section except the disclaimer is a placeholder; ``prose`` is
  empty and the composer fills it. A deterministic layer that "helpfully" wrote a sentence would
  be writing an unattributed, ungrounded sentence, and the grounding gate has no way to check a
  sentence nothing generated.
* **It claims no grounding.** Material carries claim ids so the composer can cite them; it does
  not assert that anything is supported by them. Support is the gate's verdict, not this
  module's.

Two structural rules hold on every brief this module can produce, quiet or busy:

* **What Changed Since Yesterday is always present.** The spec calls it the section users trust
  most, and a brief that silently dropped it on the day nothing could be compared would be
  hiding exactly the fact the reader needs. When the comparison cannot be made, the section says
  so.
* **The disclaimer is always last.** :data:`FINAL_DISCLAIMER` is fixed text, reproduced verbatim
  in every brief and every export (spec, S23.2).
"""

from __future__ import annotations

import datetime
import uuid
from collections.abc import Sequence
from dataclasses import dataclass, field
from enum import StrEnum

from services.reports.context import (
    AnalogyContext,
    BriefContext,
    EventEvidenceContext,
    EventForecast,
    ImmutableJSON,
    freeze_json,
)
from services.reports.contracts import (
    AlertStateChange,
    BriefInputs,
    DataQuality,
    DataQualityNote,
    RiskKey,
    SelectedEvent,
)

#: The exact, immutable financial disclaimer (report-generation spec, S23.2). Reproduced
#: verbatim in every brief and every export; it is a fixed template block, never composed, never
#: paraphrased, and never regenerated by a model.
FINAL_DISCLAIMER = (
    "This system provides probabilistic analysis based on public information, data signals, "
    "and model-assisted reasoning. It is for informational purposes only and does not "
    "constitute investment, legal, or financial advice."
)


class SectionKind(StrEnum):
    """Every section a daily brief can contain. There is no Watchlist: it is deferred to
    Phase 6 (report-generation spec) because it is per-user and the brief is a global artifact.
    """

    EXECUTIVE_SUMMARY = "executive_summary"
    TOP_EVENT = "top_event"
    RISK_RADAR = "risk_radar"
    HISTORICAL_PARALLELS = "historical_parallels"
    FORECASTS = "forecasts"
    ALERTS = "alerts"
    WHAT_CHANGED = "what_changed"
    DATA_QUALITY = "data_quality"
    DISCLAIMER = "disclaimer"


#: The brief's stable reading order: the lede, then the stories, then the standing tables, then
#: what we could not see, then the disclaimer. Fixed rather than derived, so that a reader who
#: opens Tuesday's brief finds Monday's structure -- and so that a section cannot be reordered
#: into a position that changes what it appears to claim.
SECTION_ORDER: tuple[SectionKind, ...] = (
    SectionKind.EXECUTIVE_SUMMARY,
    SectionKind.TOP_EVENT,
    SectionKind.RISK_RADAR,
    SectionKind.HISTORICAL_PARALLELS,
    SectionKind.FORECASTS,
    SectionKind.ALERTS,
    SectionKind.WHAT_CHANGED,
    SectionKind.DATA_QUALITY,
    SectionKind.DISCLAIMER,
)

#: "take top 5" (report-generation spec). Zero on a quiet day: the section shrinks, never pads.
MAX_TOP_EVENT_SECTIONS = 5


# --------------------------------------------------------------------------------------
# Structured rows
# --------------------------------------------------------------------------------------


@dataclass(frozen=True)
class RiskRadarRow:
    """One risk's standing score, and its movement if it can be measured."""

    key: RiskKey
    score: float
    level: str
    as_of: datetime.datetime
    previous_score: float | None
    previous_level: str | None
    #: Signed: positive is a risk that rose, negative one that eased. ``None`` when the risk was
    #: first observed inside this window and so has no prior score to move from -- which is not
    #: a move of zero, and is not a jump from zero either.
    delta: float | None
    is_reversal: bool

    @property
    def comparison_available(self) -> bool:
        return self.previous_level is not None


@dataclass(frozen=True)
class ForecastRow:
    """One scenario of one event's current MECE set. Table only -- never narrated here."""

    event_id: uuid.UUID
    event_title: str
    scenario_set_id: uuid.UUID
    scenario_name: str
    probability: float
    risk_score: float
    severity: str
    horizon: str
    confidence: float | None
    #: Provenance JSON, deep-frozen on construction (:func:`freeze_json`). Its source -- a
    #: :class:`ForecastScenarioRow` -- is already frozen; this re-freeze keeps the guarantee
    #: local to the material row and holds even if a caller builds one by hand.
    evidence_refs: ImmutableJSON | None

    def __post_init__(self) -> None:
        object.__setattr__(self, "evidence_refs", freeze_json(self.evidence_refs))


@dataclass(frozen=True)
class AlertRow:
    """One alert state change. List only."""

    alert_id: uuid.UUID
    title: str
    state: str
    #: The severity the change is *judged* at -- an all-clear's peak, not its decayed Low.
    severity: str
    is_all_clear: bool
    changed_at: datetime.datetime
    related_event_id: uuid.UUID | None


@dataclass(frozen=True)
class ChangeRow:
    """One risk's day-over-day movement, as What Changed Since Yesterday reports it."""

    key: RiskKey
    previous_level: str
    current_level: str
    previous_score: float
    current_score: float
    #: Signed, so the direction is in the data and not only in the prose.
    delta: float
    #: The *level* changed, not merely the score. The spec's day-over-day rule turns on this:
    #: "any reversal must be acknowledged explicitly", and an unacknowledged one fails the
    #: grounding gate -- so the material flags it rather than leaving the composer to notice.
    is_reversal: bool

    @property
    def direction(self) -> str:
        if self.delta > 0:
            return "rose"
        if self.delta < 0:
            return "eased"
        return "unchanged"


