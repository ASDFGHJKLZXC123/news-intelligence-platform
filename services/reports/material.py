@dataclass(frozen=True)
class SectionMaterial:
    """One section's slot in the brief, with its structured rows and its citable claims.

    ``prose`` is empty for every section except the disclaimer, whose text is fixed. That is the
    seam: everything in here is deterministic, and everything the composer adds is prose.
    """

    kind: SectionKind
    order: int
    title: str
    #: Non-empty only where the text is *fixed* (the disclaimer). Never model output.
    prose: str = ""
    #: The claims the composer may cite in this section, and the only ids that may reach
    #: `report_sections.evidence_refs`. Claim ids -- never a historical episode id, which would
    #: resolve through `claim_evidence` to nothing.
    claim_ids: tuple[uuid.UUID, ...] = ()
    event: SelectedEvent | None = None
    evidence: EventEvidenceContext | None = None
    analogies: tuple[AnalogyContext, ...] = ()
    risk_rows: tuple[RiskRadarRow, ...] = ()
    forecast_rows: tuple[ForecastRow, ...] = ()
    alert_rows: tuple[AlertRow, ...] = ()
    change_rows: tuple[ChangeRow, ...] = ()
    quality_notes: tuple[DataQualityNote, ...] = ()
    #: Statements of fact about what this section could not draw on. Rendered as-is; they are
    #: not prose *about* the data, they are the absence of data, and the composer may not
    #: rewrite them away.
    notes: tuple[str, ...] = ()

    @property
    def is_placeholder(self) -> bool:
        """The composer must write this section's prose. True everywhere but the disclaimer."""
        return not self.prose


@dataclass(frozen=True)
class BriefMaterial:
    """The whole brief's deterministic skeleton, in reading order."""

    sections: tuple[SectionMaterial, ...] = field(default=())

    @property
    def kinds(self) -> tuple[SectionKind, ...]:
        return tuple(section.kind for section in self.sections)

    def of_kind(self, kind: SectionKind) -> tuple[SectionMaterial, ...]:
        return tuple(section for section in self.sections if section.kind is kind)

    @property
    def disclaimer(self) -> SectionMaterial:
        """Always the last section. See :func:`build_brief_material`."""
        return self.sections[-1]


